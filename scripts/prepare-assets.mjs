#!/usr/bin/env node
/**
 * One-off asset preparation (run with `npm run assets`; outputs are committed).
 *
 * - Splits brand-source/logo/mark.svg into the dome+ring body and the dove (DESIGN §7.2 animates
 *   them separately) and optimises both with SVGO (precision 1) → src/data/mark.generated.ts
 * - Crops + grades the tower render for the hero and the story arch (DESIGN §2) → src/assets/generated/
 * - Copies the duotone key plan and hotspot data used by the explorer.
 */
import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import sharp from 'sharp';
import { optimize } from 'svgo';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const r = (...p) => path.join(root, ...p);

/* ---------- Mark ---------- */
const DOVE_SUBPATHS = new Set([5, 7, 8, 9]); // verified visually (dove outline, inner holes, eye)

const markSrc = await readFile(r('brand-source/logo/mark.svg'), 'utf8');
const viewBox = markSrc.match(/viewBox="([^"]+)"/)?.[1] ?? '0 0 415 319';
const d = markSrc.match(/ d="([^"]+)"/)?.[1];
if (!d) throw new Error('mark.svg: no path data');
const subs = d.split(/(?=M)/);
if (subs.length !== 10) throw new Error(`mark.svg: expected 10 subpaths, got ${subs.length}`);

const optimisePath = (pathData) => {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"><path fill-rule="evenodd" d="${pathData}"/></svg>`;
  const out = optimize(svg, {
    multipass: true,
    floatPrecision: 1,
    plugins: [{ name: 'preset-default' }],
  }).data;
  const od = out.match(/ d="([^"]+)"/)?.[1];
  if (!od) throw new Error('svgo dropped the path');
  return od;
};

const body = optimisePath(subs.filter((_, i) => !DOVE_SUBPATHS.has(i)).join(''));
const dove = optimisePath(subs.filter((_, i) => DOVE_SUBPATHS.has(i)).join(''));

await mkdir(r('src/data'), { recursive: true });
await writeFile(
  r('src/data/mark.generated.ts'),
  `// Generated by scripts/prepare-assets.mjs from brand-source/logo/mark.svg. Do not edit.\n` +
    `// Fill rule: evenodd. Recolour with fill="currentColor".\n` +
    `export const markViewBox = '${viewBox}';\n` +
    `export const markBody = '${body}';\n` +
    `export const markDove = '${dove}';\n`,
);
console.log(`mark: body ${body.length} B, dove ${dove.length} B (from ${d.length} B)`);

/* ---------- Tower render crops (DESIGN §2: saturation −15 %, slightly warmer, lifted shadows) ---------- */
await mkdir(r('src/assets/generated'), { recursive: true });

const grade = (img) =>
  img
    .modulate({ saturation: 0.85 })
    // warm: a touch more red, a touch less blue; small offsets lift the shadows
    .linear([1.02, 1.0, 0.95], [6, 4, 2]);

const crops = [
  { name: 'hero-tower.jpg', left: 190, top: 110, width: 1560, height: 1950 },
  { name: 'story-balconies.jpg', left: 560, top: 900, width: 900, height: 1125 },
];

for (const c of crops) {
  await grade(sharp(r('brand-source/tower-render.jpg')).extract({ left: c.left, top: c.top, width: c.width, height: c.height }))
    .jpeg({ quality: 92, mozjpeg: true, chromaSubsampling: '4:4:4' })
    .toFile(r('src/assets/generated', c.name));
  console.log(`crop: ${c.name} ${c.width}×${c.height}`);
}

/* ---------- Explorer inputs ---------- */
await copyFile(r('brand-source/plans/keyplan-duotone.png'), r('src/assets/plans/keyplan-duotone.png'));
await copyFile(r('docs/design/keyplan-hotspots.json'), r('src/data/keyplan-hotspots.json'));
console.log('copied keyplan-duotone.png and keyplan-hotspots.json');
